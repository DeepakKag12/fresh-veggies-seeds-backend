// @desc    Create new order
// @route   POST /api/orders
// @access  Private
exports.createOrder = async (req, res) => {
  try {
    const {
      orderItems,
      shippingAddress,
      paymentMode,
      itemsPrice,
      shippingPrice,
      totalAmount
    } = req.body;

    if (orderItems && orderItems.length === 0) {
      return res.status(400).json({
        success: false,
        message: 'No order items'
      });
    }

    const order = await Order.create({
      userId: req.user._id,
      orderItems,
      shippingAddress,
      paymentMode,
      itemsPrice,
      shippingPrice,
      totalAmount
    });

    res.status(201).json({
      success: true,
      data: order
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message
    });
  }
};

